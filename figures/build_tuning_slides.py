#!/usr/bin/env python3
"""Build the three 'Ways of tuning kernels' pages from the figures.

Replaces the old single "Compiler or tuning?" slide (page 5) with:

  5  Ways of tuning kernels · 01 Bottleneck-based tuning
  6  Ways of tuning kernels · 02 Search-based tuning
  7  Ways of tuning kernels · 03 Compiler-based tuning

Figures: figures/out/loop.png (paper six-phase loop) and
figures/out/search-space.svg (generated by make_tuning_figures.py).

Run after make_tuning_figures.py:
    python3 figures/build_tuning_slides.py
"""

from __future__ import annotations

import base64
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent
OUT = HERE / "out"
INDEX = ROOT / "index.html"


def data_uri(path: pathlib.Path) -> str:
    mime = "image/svg+xml" if path.suffix == ".svg" else "image/png"
    return f"data:{mime};base64," + base64.b64encode(
        path.read_bytes()).decode("ascii")


HEAD = ('  <div class="slide-header"><span class="rh-page"></span>'
        '<span class="rh-mid">A Novel AI-Native GPU Kernel PL &middot; '
        'ATC&rsquo;26</span></div>\n'
        '  <h2>Ways of tuning kernels</h2>')


def mode_line(idx: str, name: str) -> str:
    return (f'  <p class="mode-name"><span class="mode-idx">{idx}</span>'
            f'{name}</p>')


STEPS = [
    "profile the kernel",
    "analyse the bottleneck",
    "propose a structural change",
    "implement the edit",
    "compile, measure, decide",
]

PIPES = [
    ("data tiling / blocking", "Loop Tiling / Blocking"),
    ("data stationary", "Cache Read / Stage Placeholder"),
    ("data swizzling", "Loop Reorder / Interchange"),
    ("multibuffering &amp; prefetch", "Software Pipeline (Loop Peeling)"),
    ("loop unroll", "Loop Unrolling"),
    ("vectorisation", "Vectorisation"),
    ("loop fusion", "Loop Fusion"),
    ("instruction scheduling", "Instruction Scheduling"),
]


def main() -> None:
    loop_svg = (OUT / "expert-loop.svg").read_text()
    search = data_uri(OUT / "search-space.svg")

    steps_html = "\n".join(
        f'        <div class="tune-step"><span class="n">{i}</span>'
        f'{name}</div>' for i, name in enumerate(STEPS, 1))
    pipes_html = "\n".join(
        f'      <div class="pipe-row"><span class="pipe-trick">{a}</span>'
        f'<span class="pipe-arrow">&rarr;</span>'
        f'<span class="pipe-pass">{b}</span></div>' for a, b in PIPES)

    page_a = f'''<section class="gs">
{HEAD}
{mode_line("01", "Bottleneck-based tuning")}

  <div class="tune-row">
    <figure class="fig">
      {loop_svg}
    </figure>
    <div class="tune-text">
      <div class="tune-steps">
{steps_html}
      </div>
      <p class="tune-cap"><b>Profile and analyse first</b> &middot; propose only from the bottleneck.</p>
    </div>
  </div>

  <aside class="notes">
    The expert does not start from a candidate or a search space. They profile the kernel first with Nsight Compute, analyse the bottleneck second, and only then propose a structural change, implement it, compile it and decide whether to keep it. That profile-and-analyse front half is the part a compiler pipeline cannot do and a plain search does not do.
  </aside>
</section>'''

    page_b = f'''<section class="gs">
{HEAD}
{mode_line("02", "Search-based tuning")}

  <div class="tune-row">
    <figure class="fig">
      <img src="{search}" alt="Autotuning search space: a discrete grid of configurations, tile size against pipeline stages.">
    </figure>
    <div class="tune-text">
      <p class="tune-eg"><span class="eg-tag">e.g.</span>autotune &mdash; template + knobs</p>
      <ul class="tune-list">
        <li><b>Template</b> &mdash; a skeleton with tunable knobs left open.</li>
        <li><b>Search</b> &mdash; tile sizes &middot; stages &middot; warp counts &middot; swizzle.</li>
        <li><b>No bottleneck analysis</b> &mdash; the skeleton is fixed in advance.</li>
      </ul>
      <p class="tune-cap">Prune what cannot launch, benchmark the rest.</p>
    </div>
  </div>

  <aside class="notes">
    Autotuning sits between the expert loop and a compiler pipeline. Nothing is fixed, because the pipeline is not; nothing is hand-judged, because a benchmark decides. What replaces both is a template with tunable knobs left open — tile sizes, stages, warp counts, swizzle — and a search over that space. Each point in the grid is a configuration: tile size against pipeline stages, with the N-tile, K-tile and swizzle variants making up the rest of the space. Resource limits prune much of it before anything runs — configurations past the SMEM or register limit never reach the GPU — and a benchmark decides among the rest. It never profiles the kernel or asks why it is slow, and the skeleton, warp specialisation and pipeline depth are fixed in advance.
  </aside>
</section>'''

    page_c = f'''<section class="gs">
{HEAD}
{mode_line("03", "Compiler-based tuning")}

  <div class="tune-row">
    <div class="pipe">
{pipes_html}
    </div>
    <div class="tune-text">
      <p class="tune-eg"><span class="eg-tag">e.g.</span>MLIR &middot; TVM &middot; IREE</p>
      <ul class="tune-list">
        <li><b>Schedules</b> &mdash; Halide &middot; TVM TE &middot; Accera.</li>
        <li><b>Passes</b> &mdash; the tricks become loop transformations.</li>
      </ul>
      <p class="tune-cap">Write once &middot; the pass list rewrites it the same way.</p>
    </div>
  </div>

  <aside class="notes">
    A compiler pipeline writes the kernel once and lets a pass list rewrite it the same way for each shape and each chip. The optimisation tricks map onto loop transformations: tiling becomes loop tiling and blocking, keeping data stationary becomes a cache-read stage, swizzling becomes loop reorder and interchange, multibuffering becomes software pipelining with peeling, and the rest run down the pass list to instruction scheduling. MLIR, TVM and IREE are the compilers; Halide IR, Accera and TVM's tensor expressions are scheduling DSLs that sit in front of one.
  </aside>
</section>'''

    html = INDEX.read_text()
    if "<h2>Compiler or tuning?</h2>" in html:
        i = html.index("<h2>Compiler or tuning?</h2>")
        start = html.rfind("<section", 0, i)
        end = html.index("</section>", i) + len("</section>")
    else:
        # idempotent: replace the existing three-page run
        i = html.index("<h2>Ways of tuning kernels</h2>")
        start = html.rfind("<section", 0, i)
        end = start
        for _ in range(3):
            end = html.index("</section>", end) + len("</section>")
    html = html[:start] + page_a + "\n\n" + page_b + "\n\n" + page_c + html[end:]
    INDEX.write_text(html)
    print("replaced slide 5 with three tuning pages")


if __name__ == "__main__":
    main()
